Wire rope defect graph studies are conducted on ropeways, transport systems for men/material movements in underground mines, inclines, passenger car transport systems at hydro-electric project sites, hill stations and pilgrim centres etc., in accordance with prescribed safety standards

Proof load tests are conducted on all prototype mine machinery components immediately after the manufacture to ascertain the efficacy of the predesigned safe working load.

