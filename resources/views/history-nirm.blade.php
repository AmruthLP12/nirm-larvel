<p style="text-align:justify;">
The Research &amp; Development Unit of Bharat Gold Mines Limited had a well established Rock Mechanics Cell including a Material Testing Laboratory with qualified and trained personnel to tackle the problems of stability of mine excavations in hard rock particularly at deeper levels. Advanced rock mechanics instruments, including the hydro-frac tool, were used to study the strata movement and stress build up for the assessment of stope stability.  The scientific personnel have acquired experience in this field for more than 20 years.  Based on the rock mechanics research studies carried out in the Kolar Gold Mines, new mining system were designed and adopted which resulted in better ground stability and also a decrease in the frequency and intensity of rock bursts in KGF mines.


Seismic and micro-seismic techniques were adopted to monitor the seismic activity and to predict rock bursts.  As a complement to the rock burst research programme, tests on rock specimens for their physico-mechanical properties were carried out in the Materials Testing Laboratory.


The expertise developed by the Research &amp; Development Unit of Bharat Gold Mines Limited was also utilised to carry out studies on ground control for other mining organisations including the mines of Hindustan Zinc Limited and Hutti Gold Mines Limited, on a limited scale. 


The rock mechanics investigations carried out by the units have been acknowledged as to be of very high standard in the opinion of UNDP/ILO experts who visited the R&amp;D Unit.
			
