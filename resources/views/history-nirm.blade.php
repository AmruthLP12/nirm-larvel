			<p style="text-align:justify;">Many metalliferous mines including Mosaboni mines of Hindustan Copper Limited, Mochia&amp;Balaria mines of Hindustan Zinc Limited, Hutti&amp; Chitradurga mines of Hutti Gold Mines Limited and mines of Manganese Ore (India) Limited were reaching deeper levels and were exposed to large areas of wall rocks resulting in severe ground control problems. This has called for a scientific approach based on sound rock mechanics principles to design the workings.  The civil engineering projects too, with increasing tunnelling activity and need for construction of large underground caverns require the expertise of rock mechanics engineers to tackle their problems related to site characterisation, support design, numerical modelling and blasting.

In view of above, there was an urgent need of establishing a Research Centre for Rock Mechanics and Ground Control to evolve new mining methods to promote productivity, safety and conservation in coal and non-coal mines and to solve the rock mechanics related problems being faced by the mining and civil engineering sectors in the country.
</p>
