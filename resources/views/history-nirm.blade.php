The mining activity in KGF mines was on the downward trend and the Government of India have, vide their letter dated 17th December, 1987, directed that the mines of Kolar Gold Fields be closed in a period of 7 years.


It was proposed by an Expert Group constituted by the Secretary, Department of Mines, Ministry of Steel &amp; Mines in 1987 that this Institute of Rock Mechanics and Ground Control be formed at Kolar Gold Fields with the Research &amp; Development Unit of M/s Bharat Gold Mines Limited, which had developed expertise and experience in this field and recognition from the Department of Scientific and Industrial Research of the Ministry of Science &amp; Technology as its nucleus.
