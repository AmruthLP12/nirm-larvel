<p style="text-align:justify;"> In support of establishment of a Research Institute at Kolar Gold Fields, various meetings were held under the Chairmanship of the Secretary (Mines), Department of Mines, Ministry of Steel &amp; Mines, Government of India.  In addition, the renowned experts in the field of rock mechanics viz., Prof (Dr) A. Kidybinski, International Bureau of Strata Mechanics and Dr. Yung Sam Kim, UNDP Consultant on Rock Mechanics, too recommended for the establishment of a research institute at KGF.  </p>
<h4 style="    font-size: 20px;
    font-weight: bold;
    color: #485f98;"><i class="fa fa-pencil-square-o" aria-hidden="true"></i> Government approval</h4>
<p style="text-align:justify;"> The Government of India vide their letter No.14/22/87-Met.V dated 27th January, 1988 has conveyed the sanction of the President for establishment of the Institute of Rock Mechanics and Ground Control at Kolar Gold Fields under Science &amp; Technology (Plan) at a total expenditure not exceeding Rs.200 lakhs including a foreign component of Rs.40 lakhs.

The Hon’ble Union Minister of State for Mines, Smt. Ramdulari Sinha announced the approval of the Government of India for the establishment of the Institute of Rock Mechanics and Ground Control at Kolar Gold Fields while inaugurating the fifth plenary scientific session of the working group on “Rock Bursts” of the International Bureau of Strata Mechanics at the Regional Research Laboratory, Hyderabad on Tuesday, the 2nd February, 1988.


The Institute was originally named as “Kolar Institute of Rock Mechanics and Ground Control” and registered under Karnataka Societies Registration Act, 1960 &amp; Karnataka Societies Registration Rules 1961, as an autonomous research institute under the administrative control of Ministry of Mines, Government of India.  
Subsequently the name of the Institute was changed to “National Institute of Rock Mechanics” by a resolution of the General Body.
