							<h3 class="block-head">History of NIRM</h3>
							<p style="text-align:justify;"> 
							In 1980’s, stability of underground excavations was a major problem facing the mining industry, especially with the mine workings reaching greater depths in the country. Planning and designing efforts in metalliferous mines were inadequate.  In view of this, there was an urgent need for trained and competent rock mechanics engineers to tackle problems of rock mechanics and ground control in mines. 
							
							
							There was no institute to look after the problems of hard rock mining and other civil engineering projects.  Consequently, many project authorities in India were taking the help of foreign consultants to solve their rock mechanics problems.  In view of above, there was an urgent need to supplement the above facilities by establishing a Rock Mechanics Research Centre, exclusively to tackle the problems of stability of underground excavations in hard rock mines, particularly at deeper levels, and in other civil engineering projects.  
							
							
							At Kolar Gold Fields in the state of Karnataka, gold mining activities were going on with one of the deepest underground mines in the world. The mining activities at the Kolar Gold Fields over a period of century helped the Research &amp; Development Unit of Bharat Gold Mines Limited to gain unique expertise in solving hard rock deep mining problems pertaining to rock mechanics and ground control. The uniqueness of the KGF mines was recognized by many mining institutions in the world.  
							

				The Research &amp; Development Unit of Bharat Gold Mines Limited at Kolar Gold Fields was functioning since pre-independence. The Rock Mechanics Cell and Seismic and Micro-seismic Cell of this Unit have done pioneering work in the field of rock mechanics in non-coal mines, which has been recognised internationally.  The Rock Mechanics Cell has carried out investigations on the rock mass movement, in-situ stress conditions, and the rock mass movement characteristics due to rock bursts, including laboratory investigations into the physico-mechanical and elastic properties of rock. The Seismic and Micro-seismic Cell was established with the collaboration of Bhabha Atomic Research Centre and was continuing since 1978 for evaluation and prediction of ground stability in mine excavations prone to rock burst.  Seismological analysis of the stress regime of mine excavations was carried out to delineate high in-situ stress. Seismic technique provided support to monitoring stability in large and deep excavations.

