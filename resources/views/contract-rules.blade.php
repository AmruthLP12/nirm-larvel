			    				<h3 class="block-head"></h3>
			    				<p>The National Institute of Rock Mechanics (NIRM), is an autonomous Research Institute under the Ministry of Mines, Govt. of India registered as a Society under the Karnataka Societies Registration Act, 1960.</p>
				
								<p> The Institute with its scientific manpower (sanctioned strength of 82) has been catering to the needs of various sectors like mining, civil infrastructure, hydropower, nuclear power, tunnelling, rail-roadways and several other areas related to rock mass characterisation, rock mechanics and rock engineering. Even though several of the projects taken up by the Institute are challenging and require the expertise from experienced scientists. 												
								</p>
								<p> With a view to effectively accomplish the projects  in progress and also to plan time schedule for several other projects to be taken up for execution, it is proposed to take up recruitment of various personnel purely on short-term contract basis.  Cut-off age for all categories of applicants is 45 years as on date of application. </p>
								
								<h4 style="text-align:left;font-size: 16px;color:#000;"><b>Terms &amp; Conditions of Appointment :</b></h4>
								
								<p>
								1)	Contractual appointments are not against any sanctioned post of the Institute and therefore are Purely Temporary in nature. All such appointments will be against specific project(s) and will be co- terminus with the period of the specific project.   for rendering service to the client.  Under normal conditions, no extension of the tenure of appointment shall be permitted and therefore the contract stands terminated ipso facto on completion of the tenure of appointment.
</p>
<p>
2)	The tenure of appointment shall be for a period of one year or less (as per requirement in the project).  This can be extended in steps upto a maximum of three years duration. The selected candidate will be required to enter into a Contract Agreement with specified Terms &amp; Conditions that shall be signed jointly by the appointee and the Authorised Signatory from NIRM. 

</p>

<p>
3)	The appointee shall have no claim for regularising the service at the Institute at a later date nor the Institute at any point of time will entertain any claim by the candidate for extension of term or re-appointment or regularisation of job.  Such Short Period Contractual Appointments are offered by the NIRM towards National Skill Development Mission.

</p>
<p>
4)	Cut-off age for all category of applicants for such short-term contractual appointment is 45 years.  For everything else remaining same, preference in recruitment will be given to candidates below 30-35 years of age.  This is in keeping with our mission of supporting Skill Development through short-term employment so that these candidates hone their skill at NIRM in specialised areas and apply the same in a regular job elsewhere.

</p>
<p>
5)	Further, in order to make use of the experience of skilled persons served in the same line of work, applications of retirees including voluntarily retired and those who have crossed the re-employable age (i.e 45 years and above) with a minimum of 10 years of experience in relevant field may be considered for appointment against the appropriate position/ post relevant to their field of exposure.

</p>
<p>
6)	All posts carry reservation for deserving category as per operative reservation roster for the number of posts for that category.  Hence candidates should submit their application with categorically mentioning their category (SC/ST/ OBC (Non-creamy)/ GEN). 

</p>
<p>
7)	SC/ST /OBC applicants should enclose specified/prescribed copy of the caste certificate to avail the benefit of reservation and concessions failing which their applications will be categorised under unreserved class. For all the above posts, age relaxation will be provided for reserved category candidates as per the prevailing norms of Government of India.

</p>
<p>
8)	Those who are employed in the Government /public sector/autonomous Organisations should route their application through proper channel through their concerned employer. They may submit an advance copy of their application directly to NIRM by making a mention thereof. Their formal application  routed through proper channel should reach NIRM in time failing which they should produce a No Objection Certificate  (issued in this regard/for applying to this post.) at the time of interview. 

</p>
<p>
9)	Head, Project Management Cell, will be appointing authority for all contractual employees.  The performance of the candidate in project will be monitored by the Project Leader and HoD from time to time. The Appointing Authority reserves the right to terminate the contract agreement at any point of time without assigning any reason whatsoever. 

</p>
<p>
10)	Since the recruitment is done to meet the obligations of NIRM Projects, the Project Staff are liable to be deputed  to project sites in any part of the country for satisfactorily carrying out/ accomplishment of the  project work. 
In special case, the appointee may be asked to directly report to the project site. No transfer grant is admissible for joining the duty or upon his termination from contract service. 
In case the appointee reports to office and is required to travel to project sites or elsewhere as per the requirements of the Institute, he/she shall be paid the applicable TA/DA as per the rules of the Institute applicable for contractual staff. 

</p>
<p>
11)	All contractual employees will be paid only consolidated emoluments for payment as agreed in the contract document. Therefore no other monetary liability or commitment will be entertained by NIRM. The Project Staff on contract are not entitled for any incentives/honorarium.  
If the tenure of appointment is extended beyond one year, an annual increment in the emoluments limited to 3% of current monthly emoluments.

</p>
<p>
12)	 Contract appointees will be entitled for 2½  days of Earned Leave for each completed month of service. The staff may avail maximum of 2 days Casual Leave in any one calendar month.  However, the maximum casual leave permissible in six months will be limited to 4 days only. All leave will lapse at the end of the year, there will be no carry forward of any type of leave.  No leave encashment will be admissible during the service or at the conclusion of the contract period. No study leave/deputation or lien would be permissible

</p>
<p>
13)	 The appointee shall be entitled for OPD medical  treatment (reimbursement facility) for self only at par with the applicable rule for the regular employees of the Institute subject to a maximum of Rs.25,000/- per year.

</p>

<p>
14)	The project staff will not be provided any accommodation by the Institute. Hence the permissible HRA has been included in the consolidated emoluments  itself

